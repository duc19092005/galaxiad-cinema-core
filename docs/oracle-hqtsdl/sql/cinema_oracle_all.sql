CREATE OR REPLACE PROCEDURE P_HUY_DON (p_ma_don IN NUMBER, p_ly_do IN VARCHAR2, p_trang_thai OUT VARCHAR2)
IS
  v_status VARCHAR2(20);
  v_start DATE;
BEGIN
  SELECT d.TRANG_THAI, lc.TG_BAT_DAU INTO v_status, v_start FROM DON_DAT d JOIN LICH_CHIEU lc ON lc.MA_LC = d.MA_LC WHERE d.MA_DON = p_ma_don FOR UPDATE;
