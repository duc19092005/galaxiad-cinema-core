CREATE OR REPLACE VIEW V_DOANH_THU_NGAY AS
SELECT TRUNC(NGAY_DAT) AS NGAY, COUNT(*) AS SO_DON, SUM(TONG_TIEN) AS DOANH_THU
FROM DON_DAT
WHERE TRANG_THAI IN ('DA_THANH_TOAN', 'DA_SU_DUNG')
GROUP BY TRUNC(NGAY_DAT);

CREATE OR REPLACE VIEW V_GHE_TRONG AS
SELECT lc.MA_LC, lc.TG_BAT_DAU, p.TEN_PHIM, pc.TEN_PHONG, g.MA_GHE, g.HANG_GHE, g.SO_GHE, g.LOAI_GHE
FROM LICH_CHIEU lc
JOIN PHIM p ON p.MA_PHIM = lc.MA_PHIM
JOIN PHONG_CHIEU pc ON pc.MA_PHONG = lc.MA_PHONG
JOIN GHE g ON g.MA_PHONG = pc.MA_PHONG
WHERE lc.TRANG_THAI = 'DANG_MO'
  AND NOT EXISTS (SELECT 1 FROM GHE_DA_DAT gd WHERE gd.MA_LC = lc.MA_LC AND gd.MA_GHE = g.MA_GHE);

CREATE OR REPLACE VIEW V_LICH_CHIEU_HOM_NAY AS
SELECT lc.MA_LC, p.TEN_PHIM, r.TEN_RAP, pc.TEN_PHONG, dd.TEN_DD, lc.TG_BAT_DAU, lc.TG_KET_THUC, lc.GIA_CO_BAN
FROM LICH_CHIEU lc
JOIN PHIM p ON p.MA_PHIM = lc.MA_PHIM
JOIN PHONG_CHIEU pc ON pc.MA_PHONG = lc.MA_PHONG
JOIN RAP r ON r.MA_RAP = pc.MA_RAP
JOIN DINH_DANG dd ON dd.MA_DD = lc.MA_DD
WHERE TRUNC(lc.TG_BAT_DAU) = TRUNC(SYSDATE) AND lc.TRANG_THAI = 'DANG_MO';

CREATE OR REPLACE PROCEDURE P_BAO_CAO_DOANH_THU (p_tu_ngay IN DATE, p_den_ngay IN DATE, p_ket_qua OUT SYS_REFCURSOR)
IS
BEGIN
  OPEN p_ket_qua FOR
    SELECT * FROM V_DOANH_THU_NGAY WHERE NGAY BETWEEN TRUNC(p_tu_ngay) AND TRUNC(p_den_ngay) ORDER BY NGAY;
END;
/

CREATE OR REPLACE PROCEDURE P_BAO_CAO_GHE_TRONG (p_ma_lc IN NUMBER, p_ket_qua OUT SYS_REFCURSOR)
