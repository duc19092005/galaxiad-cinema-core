CREATE OR REPLACE FUNCTION F_TINH_GIA (p_ma_lc IN NUMBER, p_ma_ghe IN NUMBER)
RETURN NUMBER
IS
  v_gia NUMBER(12,2);
BEGIN
  SELECT lc.GIA_CO_BAN * g.HE_SO_GIA INTO v_gia
  FROM LICH_CHIEU lc JOIN GHE g ON g.MA_PHONG = lc.MA_PHONG
  WHERE lc.MA_LC = p_ma_lc AND g.MA_GHE = p_ma_ghe;
  RETURN v_gia;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20010, 'Khong tim thay ghe trong lich chieu.');
END;
/

CREATE OR REPLACE PROCEDURE P_DAT_VE (
  p_ma_khach IN NUMBER,
  p_ma_nv IN NUMBER,
  p_ma_lc IN NUMBER,
  p_ds_ghe IN SYS.ODCINUMBERLIST,
  p_pt_thanh_toan IN VARCHAR2,
  p_ma_don OUT NUMBER
)
IS
  v_ma_phong NUMBER;
  v_status VARCHAR2(15);
  v_count NUMBER;
  v_total NUMBER(12,2) := 0;
  v_gia NUMBER(12,2);
BEGIN
  IF p_ds_ghe IS NULL OR p_ds_ghe.COUNT = 0 OR p_ds_ghe.COUNT > 10 THEN
    RAISE_APPLICATION_ERROR(-20011, 'Mot don chi duoc dat tu 1 den 10 ghe.');
  END IF;
  SELECT MA_PHONG, TRANG_THAI INTO v_ma_phong, v_status FROM LICH_CHIEU WHERE MA_LC = p_ma_lc FOR UPDATE;
  IF v_status <> 'DANG_MO' THEN RAISE_APPLICATION_ERROR(-20012, 'Lich chieu khong con mo ban ve.'); END IF;
  SELECT COUNT(DISTINCT COLUMN_VALUE) INTO v_count FROM TABLE(p_ds_ghe);
  IF v_count <> p_ds_ghe.COUNT THEN RAISE_APPLICATION_ERROR(-20013, 'Danh sach ghe co gia tri trung.'); END IF;
  SELECT COUNT(*) INTO v_count FROM GHE WHERE MA_PHONG = v_ma_phong AND MA_GHE IN (SELECT COLUMN_VALUE FROM TABLE(p_ds_ghe));
  IF v_count <> p_ds_ghe.COUNT THEN RAISE_APPLICATION_ERROR(-20014, 'Co ghe khong thuoc phong chieu.'); END IF;
  SELECT COUNT(*) INTO v_count FROM GHE_DA_DAT WHERE MA_LC = p_ma_lc AND MA_GHE IN (SELECT COLUMN_VALUE FROM TABLE(p_ds_ghe));
  IF v_count > 0 THEN RAISE_APPLICATION_ERROR(-20015, 'Mot hoac nhieu ghe da duoc dat.'); END IF;

  p_ma_don := SEQ_DON_DAT.NEXTVAL;
  INSERT INTO DON_DAT (MA_DON, MA_BOOKING, MA_KHACH, MA_NV, MA_LC, SO_LUONG, TONG_TIEN, PHUONG_THUC_TT, TRANG_THAI)
  VALUES (p_ma_don, 'BK' || LPAD(p_ma_don, 8, '0'), p_ma_khach, p_ma_nv, p_ma_lc, p_ds_ghe.COUNT, 0, p_pt_thanh_toan, 'CHO_TT');
  FOR i IN 1 .. p_ds_ghe.COUNT LOOP
    v_gia := F_TINH_GIA(p_ma_lc, p_ds_ghe(i));
    INSERT INTO CHI_TIET_VE (MA_CTV, MA_DON, MA_GHE, DON_GIA) VALUES (SEQ_CHI_TIET_VE.NEXTVAL, p_ma_don, p_ds_ghe(i), v_gia);
    v_total := v_total + v_gia;
  END LOOP;
  UPDATE DON_DAT SET TONG_TIEN = v_total WHERE MA_DON = p_ma_don;
  COMMIT;
EXCEPTION
  WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/

CREATE OR REPLACE PROCEDURE P_THANH_TOAN (p_ma_don IN NUMBER, p_pt_thanh_toan IN VARCHAR2, p_trang_thai OUT VARCHAR2)
